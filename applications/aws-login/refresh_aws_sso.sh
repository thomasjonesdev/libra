#!/usr/bin/env bash
#
# refresh_aws_sso.sh
#
# First-time AWS IAM Identity Center (SSO) setup and token refresh for GovCloud.
# After the first successful setup, later runs only open the browser login and
# verify identity — no repeated SSO URL/region/profile prompts.
#
# Usage:
#   bash scripts/refresh_aws_sso.sh --setup     # once (or when org defaults change)
#   bash scripts/refresh_aws_sso.sh             # refresh every ~8 hours
#   eval "$(bash scripts/refresh_aws_sso.sh --export)"
#
# Notes:
#   - Saves your chosen profile to ~/.config/aeos/aws-sso.env after setup/login.
#   - On DevOps / .dev machines with certificate trust issues, try --use-device-code
#     or ask your platform team for a programmatic IAM user.

set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"

DEFAULT_SSO_SESSION_NAME="${AWS_SSO_SESSION_NAME:-aeos-govcloud}"
DEFAULT_SSO_START_URL="${AWS_SSO_START_URL:-https://start.us-gov-west-1.us-gov-home.awsapps.com/directory/d-98671f268f#/?tab=accounts}"
DEFAULT_SSO_REGION="${AWS_SSO_REGION:-us-gov-west-1}"
DEFAULT_AWS_REGION="${AWS_DEFAULT_REGION:-us-gov-west-1}"
DEFAULT_SSO_REGISTRATION_SCOPES="${AWS_SSO_REGISTRATION_SCOPES:-sso:account:access}"
DEFAULT_SSO_ACCOUNT_ID="${AWS_SSO_ACCOUNT_ID:-359247995521}"
DEFAULT_SSO_ROLE_NAME="${AWS_SSO_ROLE_NAME:-Dev_Admin}"
DEFAULT_SSO_PROFILE="${AWS_SSO_PROFILE:-${DEFAULT_SSO_ROLE_NAME}-${DEFAULT_SSO_ACCOUNT_ID}}"

AWS_CONFIG_FILE="${AWS_CONFIG_FILE:-${HOME}/.aws/config}"
STATE_DIR="${AWS_SSO_STATE_DIR:-${HOME}/.config/aeos}"
STATE_FILE="${AWS_SSO_STATE_FILE:-${STATE_DIR}/aws-sso.env}"

PROFILE=""
MODE="refresh"
EXPORT_ENV="false"
USE_DEVICE_CODE="false"
FORCE_SETUP="false"

log() {
  printf '[aws-sso] %s\n' "$*"
}

fail() {
  printf '[aws-sso] ERROR: %s\n' "$*" >&2
  exit 1
}

usage() {
  cat <<EOF
Usage: bash scripts/refresh_aws_sso.sh [options]

Modes:
  (default)   Refresh SSO token and verify caller identity (no prompts).
  --setup     Write SSO config once if missing, then log in.
  --list      List SSO-enabled profiles found in \${AWS_CONFIG_FILE}.
  --export    Print \`export AWS_PROFILE=...\` for eval (runs login + verify first).

Options:
  --profile NAME        Override the saved/default SSO profile.
  --use-device-code     Use device-code auth instead of opening a browser.
  --force-setup         Rewrite saved SSO config even if it already exists.
  --help                Show this help text.

Saved state:
  ${STATE_FILE}

Typical workflow:
  bash scripts/refresh_aws_sso.sh --setup    # once
  bash scripts/refresh_aws_sso.sh            # every ~8 hours

Override org defaults once via environment if needed:
  AWS_SSO_ACCOUNT_ID=359247995521 \\
  AWS_SSO_ROLE_NAME=Dev_Admin \\
  bash scripts/refresh_aws_sso.sh --setup
EOF
}

require_command() {
  local command_name="$1"
  command -v "${command_name}" >/dev/null 2>&1 \
    || fail "Missing required command '${command_name}'. Install AWS CLI v2 first."
}

load_state() {
  if [[ -f "${STATE_FILE}" ]]; then
    # shellcheck disable=SC1090
    source "${STATE_FILE}"
  fi
}

quote_shell() {
  printf '%q' "$1"
}

save_state() {
  local profile_name="$1"
  mkdir -p "${STATE_DIR}"
  cat >"${STATE_FILE}" <<EOF
# Generated by scripts/refresh_aws_sso.sh
AWS_SSO_SESSION_NAME=$(quote_shell "${DEFAULT_SSO_SESSION_NAME}")
AWS_SSO_START_URL=$(quote_shell "${DEFAULT_SSO_START_URL}")
AWS_SSO_REGION=$(quote_shell "${DEFAULT_SSO_REGION}")
AWS_DEFAULT_REGION=$(quote_shell "${DEFAULT_AWS_REGION}")
AWS_SSO_REGISTRATION_SCOPES=$(quote_shell "${DEFAULT_SSO_REGISTRATION_SCOPES}")
AWS_SSO_ACCOUNT_ID=$(quote_shell "${DEFAULT_SSO_ACCOUNT_ID}")
AWS_SSO_ROLE_NAME=$(quote_shell "${DEFAULT_SSO_ROLE_NAME}")
AWS_SSO_PROFILE=$(quote_shell "${profile_name}")
EOF
  chmod 600 "${STATE_FILE}" 2>/dev/null || true
}

list_sso_profiles() {
  if [[ ! -f "${AWS_CONFIG_FILE}" ]]; then
    return 0
  fi

  awk '
    /^\[profile / {
      profile = substr($0, 10, length($0) - 10)
      sso = 0
    }
    /^sso_start_url[[:space:]]*=|^sso_session[[:space:]]*=|^sso_account_id[[:space:]]*=/ {
      if (profile != "") sso = 1
    }
    /^\[/ && profile != "" {
      if (sso) print profile
      profile = ""
      sso = 0
    }
    END {
      if (profile != "" && sso) print profile
    }
  ' "${AWS_CONFIG_FILE}" | sort -u
}

profile_configured() {
  local profile_name="$1"
  aws configure list-profiles 2>/dev/null | grep -Fxq "${profile_name}"
}

sso_session_configured() {
  aws configure get "sso-session.${DEFAULT_SSO_SESSION_NAME}.sso_start_url" >/dev/null 2>&1
}

profile_for_session() {
  local session_name="$1"
  awk -v session="${session_name}" '
    /^\[profile / {
      profile = substr($0, 10, length($0) - 10)
      linked_session = ""
    }
    /^sso_session[[:space:]]*=/ {
      if (profile != "") {
        split($0, parts, "=")
        linked_session = parts[2]
        gsub(/^[[:space:]]+|[[:space:]]+$/, "", linked_session)
      }
    }
    /^\[/ && profile != "" {
      if (linked_session == session) print profile
      profile = ""
      linked_session = ""
    }
    END {
      if (profile != "" && linked_session == session) print profile
    }
  ' "${AWS_CONFIG_FILE}" 2>/dev/null | head -n 1
}

bootstrap_sso_config() {
  local profile_name="$1"

  log "Writing SSO config for session '${DEFAULT_SSO_SESSION_NAME}' and profile '${profile_name}'..."
  aws configure set "sso-session.${DEFAULT_SSO_SESSION_NAME}.sso_start_url" "${DEFAULT_SSO_START_URL}"
  aws configure set "sso-session.${DEFAULT_SSO_SESSION_NAME}.sso_region" "${DEFAULT_SSO_REGION}"
  aws configure set "sso-session.${DEFAULT_SSO_SESSION_NAME}.sso_registration_scopes" "${DEFAULT_SSO_REGISTRATION_SCOPES}"
  aws configure set "profile.${profile_name}.sso_session" "${DEFAULT_SSO_SESSION_NAME}"
  aws configure set "profile.${profile_name}.sso_account_id" "${DEFAULT_SSO_ACCOUNT_ID}"
  aws configure set "profile.${profile_name}.sso_role_name" "${DEFAULT_SSO_ROLE_NAME}"
  aws configure set "profile.${profile_name}.region" "${DEFAULT_AWS_REGION}"
}

ensure_sso_configured() {
  local profile_name="$1"

  if [[ "${FORCE_SETUP}" == "true" ]] || ! sso_session_configured || ! profile_configured "${profile_name}"; then
    bootstrap_sso_config "${profile_name}"
  else
    log "SSO config already present for profile '${profile_name}'."
  fi
}

resolve_profile() {
  load_state

  if [[ -n "${PROFILE}" ]]; then
    profile_configured "${PROFILE}" \
      || fail "Profile '${PROFILE}' was not found. Run --setup or --list."
    printf '%s' "${PROFILE}"
    return 0
  fi

  if [[ -n "${AWS_SSO_PROFILE:-}" ]] && profile_configured "${AWS_SSO_PROFILE}"; then
    printf '%s' "${AWS_SSO_PROFILE}"
    return 0
  fi

  if [[ -n "${AWS_PROFILE:-}" ]] && profile_configured "${AWS_PROFILE}"; then
    printf '%s' "${AWS_PROFILE}"
    return 0
  fi

  local session_profile=""
  session_profile="$(profile_for_session "${DEFAULT_SSO_SESSION_NAME}" || true)"
  if [[ -n "${session_profile}" ]] && profile_configured "${session_profile}"; then
    printf '%s' "${session_profile}"
    return 0
  fi

  if profile_configured "${DEFAULT_SSO_PROFILE}"; then
    printf '%s' "${DEFAULT_SSO_PROFILE}"
    return 0
  fi

  mapfile -t profiles < <(list_sso_profiles)
  if (( ${#profiles[@]} == 1 )); then
    printf '%s' "${profiles[0]}"
    return 0
  fi
  if (( ${#profiles[@]} > 1 )); then
    log "Multiple SSO profiles found:"
    printf '  - %s\n' "${profiles[@]}"
    fail "Pass --profile <name> or set AWS_SSO_PROFILE in ${STATE_FILE}."
  fi

  fail "No SSO profile found. Run: bash scripts/refresh_aws_sso.sh --setup"
}

sso_login_args() {
  local -a args=(sso login)
  if [[ "${USE_DEVICE_CODE}" == "true" ]]; then
    args+=(--use-device-code)
  fi
  printf '%s\0' "${args[@]}"
}

run_setup() {
  require_command aws
  load_state

  local profile
  profile="$(resolve_profile 2>/dev/null || printf '%s' "${DEFAULT_SSO_PROFILE}")"

  if [[ "${FORCE_SETUP}" != "true" ]] \
    && sso_session_configured \
    && profile_configured "${profile}"; then
    log "SSO is already configured for '${profile}'. Skipping prompts and refreshing login..."
    run_refresh_for_profile "${profile}"
    return 0
  fi

  log "Bootstrapping SSO config with org defaults (no interactive aws configure sso prompts)..."
  log "  session:  ${DEFAULT_SSO_SESSION_NAME}"
  log "  profile:  ${profile}"
  log "  account:  ${DEFAULT_SSO_ACCOUNT_ID}"
  log "  role:     ${DEFAULT_SSO_ROLE_NAME}"

  ensure_sso_configured "${profile}"
  run_refresh_for_profile "${profile}"
}

run_list() {
  require_command aws
  load_state
  mapfile -t profiles < <(list_sso_profiles)
  if (( ${#profiles[@]} == 0 )); then
    log "No SSO profiles found in ${AWS_CONFIG_FILE}."
    log "Run: bash scripts/refresh_aws_sso.sh --setup"
    return 0
  fi

  log "SSO profiles in ${AWS_CONFIG_FILE}:"
  printf '  - %s\n' "${profiles[@]}"
  if [[ -f "${STATE_FILE}" ]]; then
    log "Saved default profile in ${STATE_FILE}:"
    log "  AWS_SSO_PROFILE=${AWS_SSO_PROFILE:-unknown}"
  fi
}

run_refresh_for_profile() {
  local profile="$1"
  local -a login_args=()
  local arg

  save_state "${profile}"

  log "Refreshing SSO session for profile '${profile}'..."
  while IFS= read -r -d '' arg; do
    login_args+=("${arg}")
  done < <(sso_login_args)

  if ! aws "${login_args[@]}" --profile "${profile}"; then
    cat <<EOF >&2

[aws-sso] SSO login failed.

Try:
  bash scripts/refresh_aws_sso.sh --use-device-code
  bash scripts/refresh_aws_sso.sh --list

If you are on a DevOps / .dev machine with certificate trust errors, SSO may not
work in the browser and you may need a programmatic IAM user instead.

EOF
    exit 1
  fi

  log "Verifying caller identity..."
  aws sts get-caller-identity --profile "${profile}"

  if [[ "${EXPORT_ENV}" == "true" ]]; then
    printf 'export AWS_PROFILE=%q\n' "${profile}"
  else
    log "Saved default profile to ${STATE_FILE}"
    log "Next refresh (no prompts): bash scripts/refresh_aws_sso.sh"
    log "Active profile for this shell:"
    log "  export AWS_PROFILE=${profile}"
  fi
}

run_refresh() {
  require_command aws
  local profile
  profile="$(resolve_profile)"
  run_refresh_for_profile "${profile}"
}

while [[ $# -gt 0 ]]; do
  case "$1" in
    --setup)
      MODE="setup"
      ;;
    --list|--list-profiles)
      MODE="list"
      ;;
    --export)
      EXPORT_ENV="true"
      ;;
    --use-device-code)
      USE_DEVICE_CODE="true"
      ;;
    --force-setup)
      FORCE_SETUP="true"
      ;;
    --profile)
      shift
      [[ $# -gt 0 ]] || fail "--profile requires a value."
      PROFILE="$1"
      ;;
    --help|-h)
      usage
      exit 0
      ;;
    *)
      fail "Unknown option '$1'. Run with --help for usage."
      ;;
  esac
  shift
done

case "${MODE}" in
  setup)
    run_setup
    ;;
  list)
    run_list
    ;;
  refresh)
    run_refresh
    ;;
esac
