//! Build-time helpers for compiling an app's root `.lx` view through
//! `libra-codegen` (ARCHITECTURE.md §6.4, PLAN-PACKAGE P0).
//!
//! App crates call [`compile_app`] from a `build.rs` script; the generated
//! `OUT_DIR/view.rs` is included by `libra::app!` in release builds.

use libra_codegen::{generate_component_fn, generate_with_registry, Config};
use libra_markup::{parse_file, ComponentRegistry, LxFile};
use std::path::{Path, PathBuf};

/// Inputs for [`compile_app`]. Paths in `view` are relative to `manifest_dir`
/// (typically `CARGO_MANIFEST_DIR`).
pub struct AppBuildConfig {
    pub manifest_dir: PathBuf,
    /// Root view file, e.g. `"views/counter.lx"`.
    pub view: String,
    /// State type path, e.g. `"crate::Counter"`.
    pub state: String,
    /// Action enum path, e.g. `"crate::Action"`.
    pub action: String,
}

/// Parse the root view, discover sibling components, emit `OUT_DIR/view.rs`
/// containing `build_view(state) -> ViewNode`, and set
/// `cargo:rustc-cfg=libra_has_view_codegen` for the app crate.
pub fn compile_app(config: &AppBuildConfig) {
    let view_path = config.manifest_dir.join(&config.view);
    println!("cargo:rerun-if-changed={}", view_path.display());

    let view_dir = view_path
        .parent()
        .unwrap_or_else(|| panic!("view path has no parent: {}", config.view));
    rerun_if_changed_lx_under(view_dir);

    let src = std::fs::read_to_string(&view_path)
        .unwrap_or_else(|e| panic!("read {}: {e}", view_path.display()));
    let ast = match parse_file(&src).unwrap_or_else(|e| panic!("{}:{e}", view_path.display())) {
        LxFile::View(node) => node,
        LxFile::Component(_) => {
            panic!(
                "{}: root view file must be a view, not a component",
                view_path.display()
            );
        }
    };

    let registry = ComponentRegistry::load_from_dir(view_dir)
        .unwrap_or_else(|e| panic!("component registry: {e}"));

    let cfg = Config {
        state: config.state.clone(),
        action: config.action.clone(),
        fn_name: "build_view".to_string(),
        source: view_path.display().to_string(),
    };

    let mut code = String::from("// @generated by libra-build — do not edit.\n");
    for (_, def) in registry.iter() {
        code.push_str(
            &libra_codegen::generate_component_fn(def, &cfg, &registry)
                .unwrap_or_else(|e| panic!("component codegen: {e}")),
        );
        code.push('\n');
    }
    code.push_str(
        &libra_codegen::generate_with_registry(&ast, &cfg, &registry)
            .unwrap_or_else(|e| panic!("{}:{e}", view_path.display())),
    );

    let out_dir = std::env::var("OUT_DIR").expect("OUT_DIR");
    std::fs::write(Path::new(&out_dir).join("view.rs"), code).expect("write view.rs");
    // Declared for `libra::app!` cfg branches in the app crate (§6.4).
    println!("cargo:rustc-check-cfg=cfg(libra_has_view_codegen)");
    println!("cargo:rustc-cfg=libra_has_view_codegen");
}

fn rerun_if_changed_lx_under(dir: &Path) {
    let Ok(entries) = std::fs::read_dir(dir) else {
        return;
    };
    for entry in entries.flatten() {
        let path = entry.path();
        if path.is_dir() {
            rerun_if_changed_lx_under(&path);
        } else if path.extension().is_some_and(|e| e == "lx") {
            println!("cargo:rerun-if-changed={}", path.display());
        }
    }
}
