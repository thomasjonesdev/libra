//! libra-codegen — the release engine (ARCHITECTURE.md §6.4): compile a
//! parsed `.lx` AST to a static Rust `fn(state) -> ViewNode`.
//!
//! Bindings compile to direct field accesses and handlers to real
//! Action references — so a typo'd binding or handler is a **rustc
//! compile error** (§6.5), not a runtime surprise. Each generated
//! expression carries a `// file:line:col` trailer so error snippets
//! point back into the markup.
//!
//! The generator is a fold over the *same AST* the interpreter walks;
//! its semantic table (defaults, attr names, text-joining rules) must
//! mirror libra-interp exactly. The conformance suite asserts
//! `interp(state, ast) == codegen(ast)(state)` over golden fixtures —
//! any drift is a failing test, not a shipped bug.

use libra_markup::{Attr, AttrValue, Inline, Node, Span};

#[derive(Debug, Clone)]
pub struct CodegenError {
    pub message: String,
    pub span: Span,
}

impl std::fmt::Display for CodegenError {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        write!(f, "{}: {}", self.span, self.message)
    }
}
impl std::error::Error for CodegenError {}

fn err(span: Span, msg: impl Into<String>) -> CodegenError {
    CodegenError { message: msg.into(), span }
}

pub struct Config {
    /// Type path of the app's State (e.g. `crate::Counter`).
    pub state: String,
    /// Type path of the app's Action enum (e.g. `crate::Action`).
    pub action: String,
    /// Name of the generated function.
    pub fn_name: String,
    /// Source file name, for `// file:line:col` trailers.
    pub source: String,
}

pub fn generate(ast: &Node, cfg: &Config) -> Result<String, CodegenError> {
    let body = gen_node(ast, cfg, 1)?;
    Ok(format!(
        "// @generated by libra-codegen from {src} — do not edit.\n\
         #[allow(clippy::all)]\n\
         pub fn {name}(state: &{state}) -> ::libra_components::ViewNode {{\n\
         {body}\n\
         }}\n",
        src = cfg.source,
        name = cfg.fn_name,
        state = cfg.state,
        body = body,
    ))
}

fn indent(depth: usize) -> String {
    "    ".repeat(depth)
}

fn at(cfg: &Config, span: Span) -> String {
    format!("// {}:{}", cfg.source, span)
}

fn gen_node(node: &Node, cfg: &Config, d: usize) -> Result<String, CodegenError> {
    let Node::Element { name, attrs, children, span } = node else {
        return Err(err(
            Span { line: 0, col: 0 },
            "text content is only allowed inside <Text> and <Button>",
        ));
    };
    let i = indent(d);

    match name.as_str() {
        "Column" | "Row" => {
            // Mirror of interp's BoxStyle table.
            let (mut gap, mut padding, mut grow, mut cross, mut main) =
                (0.0f32, 0.0f32, false, false, false);
            for a in attrs {
                match (a.name.as_str(), &a.value) {
                    ("gap", AttrValue::Num(v)) => gap = *v,
                    ("padding", AttrValue::Num(v)) => padding = *v,
                    ("grow", AttrValue::Flag) => grow = true,
                    ("cross", AttrValue::Str(s)) if s == "center" => cross = true,
                    ("main", AttrValue::Str(s)) if s == "center" => main = true,
                    _ => return Err(unknown_attr(name, a)),
                }
            }
            if children.iter().any(|c| matches!(c, Node::Text(_))) {
                return Err(err(*span, format!("<{name}> cannot contain bare text; wrap it in <Text>")));
            }
            let kids = children
                .iter()
                .map(|c| gen_node(c, cfg, d + 2))
                .collect::<Result<Vec<_>, _>>()?
                .join(",\n");
            Ok(format!(
                "{i}::libra_components::ViewNode::{name} {{ {at}\n\
                 {i}    style: ::libra_components::BoxStyle {{ gap: {gap}, padding: {padding}, grow: {grow}, cross_center: {cross}, main_center: {main} }},\n\
                 {i}    children: ::std::vec![\n{kids}\n{i}    ],\n\
                 {i}}}",
                at = at(cfg, *span),
                gap = f32_lit(gap),
                padding = f32_lit(padding),
            ))
        }

        "Text" => {
            // Mirror of interp's Text table (size default Md).
            let mut size = "Md";
            let (mut bold, mut muted, mut grow) = (false, false, false);
            let mut test_id: Option<String> = None;
            for a in attrs {
                match (a.name.as_str(), &a.value) {
                    ("size", AttrValue::Str(s)) => {
                        size = match s.as_str() {
                            "sm" => "Sm",
                            "md" => "Md",
                            "xl" => "Xl",
                            other => {
                                return Err(err(
                                    a.span,
                                    format!("unknown size \"{other}\" — expected \"sm\", \"md\" or \"xl\""),
                                ))
                            }
                        }
                    }
                    ("bold", AttrValue::Flag) => bold = true,
                    ("muted", AttrValue::Flag) => muted = true,
                    ("grow", AttrValue::Flag) => grow = true,
                    ("testId", AttrValue::Str(s)) => test_id = Some(s.clone()),
                    _ => return Err(unknown_attr(name, a)),
                }
            }
            let content = gen_text_content(children, cfg, *span, d + 1)?;
            Ok(format!(
                "{i}::libra_components::ViewNode::Text {{ {at}\n\
                 {i}    content: {content},\n\
                 {i}    size: ::libra_components::TextSize::{size},\n\
                 {i}    bold: {bold}, muted: {muted}, grow: {grow},\n\
                 {i}    test_id: {tid},\n\
                 {i}}}",
                at = at(cfg, *span),
                tid = opt_str(&test_id),
            ))
        }

        "Button" => {
            let mut variant = "Secondary";
            let mut on_press: Option<(String, Span)> = None;
            let mut test_id: Option<String> = None;
            for a in attrs {
                match (a.name.as_str(), &a.value) {
                    ("variant", AttrValue::Str(s)) => {
                        variant = match s.as_str() {
                            "primary" => "Primary",
                            "secondary" => "Secondary",
                            "ghost" => "Ghost",
                            other => {
                                return Err(err(
                                    a.span,
                                    format!("unknown variant \"{other}\" — expected \"primary\", \"secondary\" or \"ghost\""),
                                ))
                            }
                        }
                    }
                    ("onPress", AttrValue::Ident(m)) => on_press = Some((m.clone(), a.span)),
                    ("testId", AttrValue::Str(s)) => test_id = Some(s.clone()),
                    _ => return Err(unknown_attr(name, a)),
                }
            }
            let (msg, mspan) =
                on_press.ok_or_else(|| err(*span, "<Button> requires onPress={someAction}"))?;
            let label = gen_text_content(children, cfg, *span, d + 1)?;
            // `let _ = &Msg::X;` — a typo'd handler is a rustc error at
            // the line carrying the .lx span (§6.5).
            Ok(format!(
                "{i}::libra_components::ViewNode::Button {{ {at}\n\
                 {i}    label: {label},\n\
                 {i}    variant: ::libra_components::Variant::{variant},\n\
                 {i}    on_press: {{ let _ = &{msg_ty}::{msg}; {name_lit}.to_string() }}, {mat}\n\
                 {i}    test_id: {tid},\n\
                 {i}}}",
                at = at(cfg, *span),
                msg_ty = cfg.action,
                name_lit = str_lit(&msg),
                mat = at(cfg, mspan),
                tid = opt_str(&test_id),
            ))
        }

        "Chart" | "Sparkline" => {
            let mut handle: Option<(String, Span)> = None;
            let mut width = 60.0f32;
            let mut height: f32 = if name == "Chart" { 120.0 } else { 20.0 };
            let mut test_id: Option<String> = None;
            for a in attrs {
                match (a.name.as_str(), &a.value) {
                    ("series", AttrValue::Ident(path)) => handle = Some((path.clone(), a.span)),
                    ("height", AttrValue::Num(v)) => height = *v,
                    ("width", AttrValue::Num(v)) if name == "Sparkline" => width = *v,
                    ("testId", AttrValue::Str(s)) => test_id = Some(s.clone()),
                    _ => return Err(unknown_attr(name, a)),
                }
            }
            let (path, hspan) = handle
                .ok_or_else(|| err(*span, format!("<{name}> requires series={{someHandle}}")))?;
            // Typed access: `state.s0` must be a SeriesHandle or rustc
            // objects at this line.
            let extra = if name == "Sparkline" {
                format!("width: {}, ", f32_lit(width))
            } else {
                String::new()
            };
            Ok(format!(
                "{i}::libra_components::ViewNode::{name} {{ {at}\n\
                 {i}    handle: state.{path}, {hat}\n\
                 {i}    {extra}height: {height},\n\
                 {i}    test_id: {tid},\n\
                 {i}}}",
                at = at(cfg, *span),
                hat = at(cfg, hspan),
                height = f32_lit(height),
                tid = opt_str(&test_id),
            ))
        }

        "Input" => {
            let mut value: Option<(String, Span)> = None;
            let mut placeholder = String::new();
            let mut on_change: Option<(String, Span)> = None;
            let mut test_id: Option<String> = None;
            for a in attrs {
                match (a.name.as_str(), &a.value) {
                    ("value", AttrValue::Ident(path)) => value = Some((path.clone(), a.span)),
                    ("placeholder", AttrValue::Str(s)) => placeholder = s.clone(),
                    ("onChange", AttrValue::Ident(m)) => on_change = Some((m.clone(), a.span)),
                    ("testId", AttrValue::Str(s)) => test_id = Some(s.clone()),
                    _ => return Err(unknown_attr(name, a)),
                }
            }
            let (path, vspan) =
                value.ok_or_else(|| err(*span, "<Input> requires value={someField}"))?;
            let (msg, mspan) =
                on_change.ok_or_else(|| err(*span, "<Input> requires onChange={someAction}"))?;
            let test_id = test_id
                .ok_or_else(|| err(*span, "<Input> requires testId=\"…\" (focus identity)"))?;
            // The `let _: fn(String) -> Msg` coercion makes "not a
            // String-payload variant" a type error at the .lx line.
            Ok(format!(
                "{i}::libra_components::ViewNode::Input {{ {at}\n\
                 {i}    value: ::std::string::ToString::to_string(&state.{path}), {vat}\n\
                 {i}    placeholder: {ph}.to_string(),\n\
                 {i}    on_change: {{ let _: fn(::std::string::String) -> {msg_ty} = {msg_ty}::{msg}; {name_lit}.to_string() }}, {mat}\n\
                 {i}    test_id: {tid}.to_string(),\n\
                 {i}}}",
                at = at(cfg, *span),
                vat = at(cfg, vspan),
                ph = str_lit(&placeholder),
                msg_ty = cfg.action,
                name_lit = str_lit(&msg),
                mat = at(cfg, mspan),
                tid = str_lit(&test_id),
            ))
        }

        other => Err(err(
            *span,
            format!(
                "unknown element <{other}> — available: Column, Row, Text, Button, Chart, Sparkline, Input"
            ),
        )),
    }
}

/// Mirrors interp's `text_content` exactly: parts joined with a single
/// space when whitespace-separated in source, result trimmed. The
/// interp's runtime algorithm is replayed in generated code so both
/// engines produce identical strings for identical models.
fn gen_text_content(
    children: &[Node],
    cfg: &Config,
    span: Span,
    d: usize,
) -> Result<String, CodegenError> {
    let i = indent(d + 1);
    let mut stmts = String::new();
    for (ci, child) in children.iter().enumerate() {
        let Node::Text(inlines) = child else {
            return Err(err(span, "nested elements inside text content are not allowed in Phase 0"));
        };
        for (j, inline) in inlines.iter().enumerate() {
            if (ci, j) != (0, 0) {
                stmts.push_str(&format!(
                    "{i}if !out.is_empty() && !out.ends_with(' ') {{ out.push(' '); }}\n"
                ));
            }
            match inline {
                Inline::Lit(s) => {
                    stmts.push_str(&format!("{i}out.push_str({});\n", str_lit(s)));
                }
                Inline::Bind { path, span } => {
                    stmts.push_str(&format!(
                        "{i}out.push_str(&::std::string::ToString::to_string(&state.{path})); {}\n",
                        at(cfg, *span)
                    ));
                }
            }
        }
    }
    Ok(format!(
        "{{\n{i}let mut out = ::std::string::String::new();\n{stmts}{i}out.trim().to_string()\n{pad}}}",
        pad = indent(d),
    ))
}

fn unknown_attr(el: &str, a: &Attr) -> CodegenError {
    err(a.span, format!("unknown or invalid attribute '{}' on <{el}>", a.name))
}

fn f32_lit(v: f32) -> String {
    format!("{v}f32")
}

fn str_lit(s: &str) -> String {
    format!("{s:?}")
}

fn opt_str(s: &Option<String>) -> String {
    match s {
        Some(v) => format!("::core::option::Option::Some({}.to_string())", str_lit(v)),
        None => "::core::option::Option::None".to_string(),
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    fn cfg() -> Config {
        Config {
            state: "crate::TestState".into(),
            action: "crate::TestAction".into(),
            fn_name: "build_view".into(),
            source: "test.lx".into(),
        }
    }

    #[test]
    fn generates_typed_accesses_and_span_trailers() {
        let ast = libra_markup::parse(
            "<Column gap={12}>\n  <Text testId=\"c\">{count}</Text>\n  <Button onPress={Increment}>+</Button>\n</Column>",
        )
        .unwrap();
        let code = generate(&ast, &cfg()).unwrap();
        assert!(code.contains("&state.count"), "bindings become field accesses");
        assert!(code.contains("crate::TestAction::Increment"), "handlers become real Action refs");
        assert!(code.contains("// test.lx:2:"), "expressions carry .lx spans");
        assert!(code.starts_with("// @generated"));
    }

    #[test]
    fn unknown_element_is_a_codegen_error_with_span() {
        let ast = libra_markup::parse("<Colunm></Colunm>").unwrap();
        let e = generate(&ast, &cfg()).unwrap_err();
        assert!(e.message.contains("unknown element <Colunm>"));
        assert_eq!(e.span.line, 1);
    }

    #[test]
    fn input_requires_test_id_at_generation_time() {
        let ast = libra_markup::parse(
            "<Column><Input value={name} onChange={NameChanged} /></Column>",
        )
        .unwrap();
        let e = generate(&ast, &cfg()).unwrap_err();
        assert!(e.message.contains("requires testId"));
    }
}
