//! libra-codegen — the release engine (ARCHITECTURE.md §6.4): compile a
//! parsed `.lx` AST to a static Rust `fn(state) -> ViewNode`.
//!
//! Bindings compile to direct field accesses and handlers to real
//! Action references — so a typo'd binding or handler is a **rustc
//! compile error** (§6.5), not a runtime surprise. Each generated
//! expression carries a `// file:line:col` trailer so error snippets
//! point back into the markup.
//!
//! The generator is a fold over the *same AST* the interpreter walks;
//! its semantic table (defaults, attr names, text-joining rules) must
//! mirror libra-interp exactly. The conformance suite asserts
//! `interp(state, ast) == codegen(ast)(state)` over golden fixtures —
//! any drift is a failing test, not a shipped bug.

use libra_markup::{Attr, AttrValue, Inline, Node, Span};

#[derive(Debug, Clone)]
pub struct CodegenError {
    pub message: String,
    pub span: Span,
}

impl std::fmt::Display for CodegenError {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        write!(f, "{}: {}", self.span, self.message)
    }
}
impl std::error::Error for CodegenError {}

fn err(span: Span, msg: impl Into<String>) -> CodegenError {
    CodegenError { message: msg.into(), span }
}

pub struct Config {
    /// Type path of the app's State (e.g. `crate::Counter`).
    pub state: String,
    /// Type path of the app's Action enum (e.g. `crate::Action`).
    pub action: String,
    /// Name of the generated function.
    pub fn_name: String,
    /// Source file name, for `// file:line:col` trailers.
    pub source: String,
}

pub fn generate(ast: &Node, cfg: &Config) -> Result<String, CodegenError> {
    let body = gen_node(ast, cfg, 1, &[])?;
    Ok(format!(
        "// @generated by libra-codegen from {src} — do not edit.\n\
         #[allow(clippy::all)]\n\
         pub fn {name}(state: &{state}) -> ::libra_components::ViewNode {{\n\
         {body}\n\
         }}\n",
        src = cfg.source,
        name = cfg.fn_name,
        state = cfg.state,
        body = body,
    ))
}

fn indent(depth: usize) -> String {
    "    ".repeat(depth)
}

fn at(cfg: &Config, span: Span) -> String {
    format!("// {}:{}", cfg.source, span)
}

fn gen_node(node: &Node, cfg: &Config, d: usize, bound: &[String]) -> Result<String, CodegenError> {
    let Node::Element { name, attrs, children, span } = node else {
        return Err(err(
            Span { line: 0, col: 0 },
            "text content is only allowed inside <Text> and <Button>",
        ));
    };
    let i = indent(d);

    match name.as_str() {
        "Column" | "Row" => {
            // Mirror of interp's BoxStyle table.
            let (mut gap, mut padding, mut grow, mut cross, mut main) =
                (0.0f32, 0.0f32, 0.0f32, false, false);
            let mut width: Option<f32> = None;
            for a in attrs {
                match (a.name.as_str(), &a.value) {
                    ("gap", AttrValue::Num(v)) => gap = *v,
                    ("padding", AttrValue::Num(v)) => padding = *v,
                    ("grow", AttrValue::Flag) => grow = 1.0,
                    // Weighted grow (`grow={2.5}`) — responsive panes.
                    ("grow", AttrValue::Num(v)) => grow = *v,
                    ("width", AttrValue::Num(v)) => width = Some(*v),
                    ("cross", AttrValue::Str(s)) if s == "center" => cross = true,
                    ("main", AttrValue::Str(s)) if s == "center" => main = true,
                    _ => return Err(unknown_attr(name, a)),
                }
            }
            let kids = gen_children(children, cfg, d + 2, bound, name, *span)?;
            Ok(format!(
                "{i}::libra_components::ViewNode::{name} {{ {at}\n\
                 {i}    style: ::libra_components::BoxStyle {{ gap: {gap}, padding: {padding}, grow: {grow}, cross_center: {cross}, main_center: {main}, width: {width} }},\n\
                 {i}    children: {kids},\n\
                 {i}}}",
                at = at(cfg, *span),
                gap = f32_lit(gap),
                padding = f32_lit(padding),
                grow = f32_lit(grow),
                width = opt_f32(width),
            ))
        }

        // §7.1 Layout (PLAN-CATALOG wave 1), matching libra-interp's
        // "Spacer" arm exactly: size xor grow; bare = spring.
        "Spacer" => {
            let mut size: Option<f32> = None;
            let mut grow = false;
            for a in attrs {
                match (a.name.as_str(), &a.value) {
                    ("size", AttrValue::Num(v)) => size = Some(*v),
                    ("grow", AttrValue::Flag) => grow = true,
                    _ => return Err(unknown_attr(name, a)),
                }
            }
            if size.is_some() && grow {
                return Err(err(*span, "<Spacer> takes size={px} or grow, not both"));
            }
            if !children.is_empty() {
                return Err(err(*span, "<Spacer> takes no children"));
            }
            Ok(format!(
                "{i}::libra_components::ViewNode::Spacer {{ {at}\n\
                 {i}    size: {size},\n\
                 {i}}}",
                at = at(cfg, *span),
                size = opt_f32(size),
            ))
        }

        // §7.1 Layout (PLAN-CATALOG wave 1), matching libra-interp's
        // "Separator" arm exactly.
        "Separator" => {
            let mut vertical = false;
            for a in attrs {
                match (a.name.as_str(), &a.value) {
                    ("vertical", AttrValue::Flag) => vertical = true,
                    _ => return Err(unknown_attr(name, a)),
                }
            }
            if !children.is_empty() {
                return Err(err(*span, "<Separator> takes no children"));
            }
            Ok(format!(
                "{i}::libra_components::ViewNode::Separator {{ {at}\n\
                 {i}    vertical: {vertical},\n\
                 {i}}}",
                at = at(cfg, *span),
            ))
        }

        "Text" => {
            // Mirror of interp's Text table (size default Md).
            let mut size = "Md";
            let (mut bold, mut muted, mut grow) = (false, false, false);
            let mut test_id: Option<String> = None;
            for a in attrs {
                match (a.name.as_str(), &a.value) {
                    ("size", AttrValue::Str(s)) => {
                        size = match s.as_str() {
                            "sm" => "Sm",
                            "md" => "Md",
                            "xl" => "Xl",
                            other => {
                                return Err(err(
                                    a.span,
                                    format!("unknown size \"{other}\" — expected \"sm\", \"md\" or \"xl\""),
                                ))
                            }
                        }
                    }
                    ("bold", AttrValue::Flag) => bold = true,
                    ("muted", AttrValue::Flag) => muted = true,
                    ("grow", AttrValue::Flag) => grow = true,
                    ("testId", AttrValue::Str(s)) => test_id = Some(s.clone()),
                    _ => return Err(unknown_attr(name, a)),
                }
            }
            let content = gen_text_content(children, cfg, *span, d + 1, bound)?;
            Ok(format!(
                "{i}::libra_components::ViewNode::Text {{ {at}\n\
                 {i}    content: {content},\n\
                 {i}    size: ::libra_components::TextSize::{size},\n\
                 {i}    bold: {bold}, muted: {muted}, grow: {grow},\n\
                 {i}    test_id: {tid},\n\
                 {i}}}",
                at = at(cfg, *span),
                tid = opt_str(&test_id),
            ))
        }

        "Button" => {
            let mut variant = "Secondary";
            // (handler name, optional arg binding, span)
            let mut on_press: Option<(String, Option<String>, Span)> = None;
            let mut test_id: Option<String> = None;
            for a in attrs {
                match (a.name.as_str(), &a.value) {
                    ("variant", AttrValue::Str(s)) => {
                        variant = match s.as_str() {
                            "primary" => "Primary",
                            "secondary" => "Secondary",
                            "ghost" => "Ghost",
                            other => {
                                return Err(err(
                                    a.span,
                                    format!("unknown variant \"{other}\" — expected \"primary\", \"secondary\" or \"ghost\""),
                                ))
                            }
                        }
                    }
                    ("onPress", AttrValue::Ident(m)) => on_press = Some((m.clone(), None, a.span)),
                    ("onPress", AttrValue::Call { name: m, arg }) => {
                        on_press = Some((m.clone(), Some(arg.clone()), a.span))
                    }
                    ("testId", AttrValue::Str(s)) => test_id = Some(s.clone()),
                    _ => return Err(unknown_attr(name, a)),
                }
            }
            let (msg, arg, mspan) =
                on_press.ok_or_else(|| err(*span, "<Button> requires onPress={someAction}"))?;
            require_camel_case(&msg, mspan)?;
            let label = gen_text_content(children, cfg, *span, d + 1, bound)?;
            // The `let _` line makes a typo'd handler a rustc error at the
            // .lx span (§6.5). Unit handlers reference the variant value
            // (`&Action::X`); item-scoped handlers (`onPress={toggle(item)}`)
            // pin the constructor to `fn(String) -> Action`, matching the
            // interpreter's `has_str_action` check, and carry the loop
            // binding's Display as the `on_press_arg` payload.
            let (check, arg_expr) = match &arg {
                Some(binding) => {
                    let value_ref = display_ref_expr(binding, bound).map_err(|m| err(mspan, m))?;
                    (
                        format!(
                            "let _: fn(::std::string::String) -> {msg_ty} = {msg_ty}::{variant_ref};",
                            msg_ty = cfg.action,
                            variant_ref = pascalize(&msg),
                        ),
                        format!(
                            "::core::option::Option::Some(::std::string::ToString::to_string(&{value_ref}))"
                        ),
                    )
                }
                None => (
                    format!("let _ = &{msg_ty}::{variant_ref};", msg_ty = cfg.action, variant_ref = pascalize(&msg)),
                    "::core::option::Option::None".to_string(),
                ),
            };
            Ok(format!(
                "{i}::libra_components::ViewNode::Button {{ {at}\n\
                 {i}    label: {label},\n\
                 {i}    variant: ::libra_components::Variant::{variant},\n\
                 {i}    on_press: {{ {check} {name_lit}.to_string() }}, {mat}\n\
                 {i}    on_press_arg: {arg_expr},\n\
                 {i}    test_id: {tid},\n\
                 {i}}}",
                at = at(cfg, *span),
                name_lit = str_lit(&msg),
                mat = at(cfg, mspan),
                tid = opt_str(&test_id),
            ))
        }

        // §7.1 (PLAN-CATALOG), matching libra-interp's "ListItem" arm
        // exactly: title/subtitle/meta as literal or binding, the
        // `selected` bool via the shared Display-"true" rule, and the
        // Button-shaped onPress/arg machinery.
        "ListItem" => {
            // (expr, is_literal) for the three text lines.
            let text_attr = |v: &AttrValue, aspan: Span| -> Result<String, CodegenError> {
                match v {
                    AttrValue::Str(s) => Ok(format!("{}.to_string()", str_lit(s))),
                    AttrValue::Ident(p) => {
                        let expr = display_ref_expr(p, bound).map_err(|m| err(aspan, m))?;
                        Ok(format!("::std::string::ToString::to_string(&{expr})"))
                    }
                    _ => Err(err(aspan, "expected a string literal or a {binding}")),
                }
            };
            let mut title: Option<String> = None;
            let mut subtitle = "::std::string::String::new()".to_string();
            let mut meta = "::std::string::String::new()".to_string();
            let mut selected = "false".to_string();
            let mut on_press: Option<(String, Option<String>, Span)> = None;
            let mut test_id: Option<String> = None;
            for a in attrs {
                match (a.name.as_str(), &a.value) {
                    ("title", v @ (AttrValue::Str(_) | AttrValue::Ident(_))) => {
                        title = Some(text_attr(v, a.span)?)
                    }
                    ("subtitle", v @ (AttrValue::Str(_) | AttrValue::Ident(_))) => {
                        subtitle = text_attr(v, a.span)?
                    }
                    ("meta", v @ (AttrValue::Str(_) | AttrValue::Ident(_))) => {
                        meta = text_attr(v, a.span)?
                    }
                    ("selected", AttrValue::Flag) => selected = "true".to_string(),
                    ("selected", AttrValue::Ident(p)) => {
                        // Same bool rule as interp: resolved Display == "true".
                        let expr = display_ref_expr(p, bound).map_err(|m| err(a.span, m))?;
                        selected =
                            format!("::std::string::ToString::to_string(&{expr}) == \"true\"");
                    }
                    ("onPress", AttrValue::Ident(m)) => on_press = Some((m.clone(), None, a.span)),
                    ("onPress", AttrValue::Call { name: m, arg }) => {
                        on_press = Some((m.clone(), Some(arg.clone()), a.span))
                    }
                    ("testId", AttrValue::Str(s)) => test_id = Some(s.clone()),
                    _ => return Err(unknown_attr(name, a)),
                }
            }
            if !children.is_empty() {
                return Err(err(*span, "<ListItem> takes no children — use title/subtitle/meta attrs"));
            }
            let title = title
                .ok_or_else(|| err(*span, "<ListItem> requires title={binding} or title=\"…\""))?;
            let (msg, arg, mspan) =
                on_press.ok_or_else(|| err(*span, "<ListItem> requires onPress={someAction}"))?;
            require_camel_case(&msg, mspan)?;
            let (check, arg_expr) = match &arg {
                Some(binding) => {
                    let value_ref = display_ref_expr(binding, bound).map_err(|m| err(mspan, m))?;
                    (
                        format!(
                            "let _: fn(::std::string::String) -> {msg_ty} = {msg_ty}::{variant_ref};",
                            msg_ty = cfg.action,
                            variant_ref = pascalize(&msg),
                        ),
                        format!(
                            "::core::option::Option::Some(::std::string::ToString::to_string(&{value_ref}))"
                        ),
                    )
                }
                None => (
                    format!("let _ = &{msg_ty}::{variant_ref};", msg_ty = cfg.action, variant_ref = pascalize(&msg)),
                    "::core::option::Option::None".to_string(),
                ),
            };
            Ok(format!(
                "{i}::libra_components::ViewNode::ListItem {{ {at}\n\
                 {i}    title: {title},\n\
                 {i}    subtitle: {subtitle},\n\
                 {i}    meta: {meta},\n\
                 {i}    selected: {selected},\n\
                 {i}    on_press: {{ {check} {name_lit}.to_string() }}, {mat}\n\
                 {i}    on_press_arg: {arg_expr},\n\
                 {i}    test_id: {tid},\n\
                 {i}}}",
                at = at(cfg, *span),
                name_lit = str_lit(&msg),
                mat = at(cfg, mspan),
                tid = opt_str(&test_id),
            ))
        }

        // §10.1 stage 1 (PLAN-TEXTAREA), matching libra-interp's
        // "Textarea" arm exactly — the Input contract, one node over.
        "Textarea" => {
            let mut value: Option<(String, Span)> = None;
            let mut placeholder = String::new();
            let mut on_change: Option<(String, Span)> = None;
            let mut test_id: Option<String> = None;
            for a in attrs {
                match (a.name.as_str(), &a.value) {
                    ("value", AttrValue::Ident(path)) => value = Some((path.clone(), a.span)),
                    ("placeholder", AttrValue::Str(s)) => placeholder = s.clone(),
                    ("onChange", AttrValue::Ident(m)) => on_change = Some((m.clone(), a.span)),
                    ("testId", AttrValue::Str(s)) => test_id = Some(s.clone()),
                    _ => return Err(unknown_attr(name, a)),
                }
            }
            let (path, vspan) =
                value.ok_or_else(|| err(*span, "<Textarea> requires value={someField}"))?;
            let value_ref = display_ref_expr(&path, bound).map_err(|m| err(vspan, m))?;
            let (msg, mspan) =
                on_change.ok_or_else(|| err(*span, "<Textarea> requires onChange={someAction}"))?;
            require_camel_case(&msg, mspan)?;
            let test_id = test_id
                .ok_or_else(|| err(*span, "<Textarea> requires testId=\"…\" (focus identity)"))?;
            Ok(format!(
                "{i}::libra_components::ViewNode::Textarea {{ {at}\n\
                 {i}    value: ::std::string::ToString::to_string(&{value_ref}),\n\
                 {i}    placeholder: {ph}.to_string(),\n\
                 {i}    on_change: {{ let _: fn(::std::string::String) -> {msg_ty} = {msg_ty}::{variant_ref}; {name_lit}.to_string() }}, {mat}\n\
                 {i}    test_id: {tid}.to_string(),\n\
                 {i}}}",
                at = at(cfg, *span),
                ph = str_lit(&placeholder),
                msg_ty = cfg.action,
                variant_ref = pascalize(&msg),
                name_lit = str_lit(&msg),
                mat = at(cfg, mspan),
                tid = str_lit(&test_id),
            ))
        }

        "Chart" | "Sparkline" => {
            let mut handle: Option<(String, Span)> = None;
            let mut width = 60.0f32;
            let mut height: f32 = if name == "Chart" { 120.0 } else { 20.0 };
            let mut test_id: Option<String> = None;
            for a in attrs {
                match (a.name.as_str(), &a.value) {
                    ("series", AttrValue::Ident(path)) => handle = Some((path.clone(), a.span)),
                    ("height", AttrValue::Num(v)) => height = *v,
                    ("width", AttrValue::Num(v)) if name == "Sparkline" => width = *v,
                    ("testId", AttrValue::Str(s)) => test_id = Some(s.clone()),
                    _ => return Err(unknown_attr(name, a)),
                }
            }
            let (path, hspan) = handle
                .ok_or_else(|| err(*span, format!("<{name}> requires series={{someHandle}}")))?;
            // Typed access: must be a SeriesHandle or rustc objects at
            // this line. `state.s0` normally; a loop-bound path (§6.2's
            // <for>) derefs the `.iter()` reference instead.
            let handle_expr = typed_value_expr(&path, bound)
                .map_err(|m| err(hspan, m))?;
            let extra = if name == "Sparkline" {
                format!("width: {}, ", f32_lit(width))
            } else {
                String::new()
            };
            Ok(format!(
                "{i}::libra_components::ViewNode::{name} {{ {at}\n\
                 {i}    handle: {handle_expr}, {hat}\n\
                 {i}    {extra}height: {height},\n\
                 {i}    test_id: {tid},\n\
                 {i}}}",
                at = at(cfg, *span),
                hat = at(cfg, hspan),
                height = f32_lit(height),
                tid = opt_str(&test_id),
            ))
        }

        "Input" => {
            let mut value: Option<(String, Span)> = None;
            let mut placeholder = String::new();
            let mut on_change: Option<(String, Span)> = None;
            let mut test_id: Option<String> = None;
            for a in attrs {
                match (a.name.as_str(), &a.value) {
                    ("value", AttrValue::Ident(path)) => value = Some((path.clone(), a.span)),
                    ("placeholder", AttrValue::Str(s)) => placeholder = s.clone(),
                    ("onChange", AttrValue::Ident(m)) => on_change = Some((m.clone(), a.span)),
                    ("testId", AttrValue::Str(s)) => test_id = Some(s.clone()),
                    _ => return Err(unknown_attr(name, a)),
                }
            }
            let (path, vspan) =
                value.ok_or_else(|| err(*span, "<Input> requires value={someField}"))?;
            let (msg, mspan) =
                on_change.ok_or_else(|| err(*span, "<Input> requires onChange={someAction}"))?;
            require_camel_case(&msg, mspan)?;
            let test_id = test_id
                .ok_or_else(|| err(*span, "<Input> requires testId=\"…\" (focus identity)"))?;
            // The `let _: fn(String) -> Action` coercion makes "not a
            // String-payload variant" a type error at the .lx line.
            // Variant reference PascalCased from the markup name, same
            // as Button's onPress above.
            let value_ref = display_ref_expr(&path, bound).map_err(|m| err(vspan, m))?;
            Ok(format!(
                "{i}::libra_components::ViewNode::Input {{ {at}\n\
                 {i}    value: ::std::string::ToString::to_string(&{value_ref}), {vat}\n\
                 {i}    placeholder: {ph}.to_string(),\n\
                 {i}    on_change: {{ let _: fn(::std::string::String) -> {msg_ty} = {msg_ty}::{variant_ref}; {name_lit}.to_string() }}, {mat}\n\
                 {i}    test_id: {tid}.to_string(),\n\
                 {i}}}",
                at = at(cfg, *span),
                vat = at(cfg, vspan),
                ph = str_lit(&placeholder),
                msg_ty = cfg.action,
                variant_ref = pascalize(&msg),
                name_lit = str_lit(&msg),
                mat = at(cfg, mspan),
                tid = str_lit(&test_id),
            ))
        }

        // §12.5: invisible, zero-layout — declares a mount-scoped
        // subscription, matching libra-interp's "Frames" arm exactly
        // (both engines share §6.4's no-drift guarantee).
        "Frames" => {
            let mut on_tick: Option<(String, Span)> = None;
            for a in attrs {
                match (a.name.as_str(), &a.value) {
                    ("onTick", AttrValue::Ident(m)) => on_tick = Some((m.clone(), a.span)),
                    _ => return Err(unknown_attr(name, a)),
                }
            }
            let (msg, mspan) =
                on_tick.ok_or_else(|| err(*span, "<Frames> requires onTick={someAction}"))?;
            require_camel_case(&msg, mspan)?;
            // `let _: fn(FrameInfo) -> Action` makes "not a
            // FrameInfo-payload variant" a type error at the .lx line,
            // same trick as Button/Input's handler checks.
            Ok(format!(
                "{i}::libra_components::ViewNode::SourceFrames {{ {at}\n\
                 {i}    on_tick: {{ let _: fn(::libra_core::FrameInfo) -> {msg_ty} = {msg_ty}::{variant_ref}; {name_lit}.to_string() }}, {mat}\n\
                 {i}}}",
                at = at(cfg, *span),
                msg_ty = cfg.action,
                variant_ref = pascalize(&msg),
                name_lit = str_lit(&msg),
                mat = at(cfg, mspan),
            ))
        }

        // §12.5: invisible, zero-layout — a recurring timer while
        // mounted, matching libra-interp's "Interval" arm exactly.
        "Interval" => {
            let mut every: Option<(u64, Span)> = None;
            let mut on_tick: Option<(String, Span)> = None;
            for a in attrs {
                match (a.name.as_str(), &a.value) {
                    ("every", AttrValue::Num(v)) => every = Some((*v as u64, a.span)),
                    ("onTick", AttrValue::Ident(m)) => on_tick = Some((m.clone(), a.span)),
                    _ => return Err(unknown_attr(name, a)),
                }
            }
            let (every_ms, _espan) =
                every.ok_or_else(|| err(*span, "<Interval> requires every={milliseconds}"))?;
            let (msg, mspan) =
                on_tick.ok_or_else(|| err(*span, "<Interval> requires onTick={someAction}"))?;
            require_camel_case(&msg, mspan)?;
            // `let _: fn(Instant) -> Action` makes "not an
            // Instant-payload variant" a type error at the .lx line,
            // same trick as Frames' FrameInfo check.
            Ok(format!(
                "{i}::libra_components::ViewNode::SourceInterval {{ {at}\n\
                 {i}    every_ms: {every_ms}u64,\n\
                 {i}    on_tick: {{ let _: fn(::libra_core::Instant) -> {msg_ty} = {msg_ty}::{variant_ref}; {name_lit}.to_string() }}, {mat}\n\
                 {i}}}",
                at = at(cfg, *span),
                msg_ty = cfg.action,
                variant_ref = pascalize(&msg),
                name_lit = str_lit(&msg),
                mat = at(cfg, mspan),
            ))
        }

        // §12.5: grammar + mount + query in v1, matching libra-interp's
        // "Stream" arm exactly. Full event delivery is a later change.
        "Stream" => {
            let mut id: Option<(String, Span)> = None;
            let mut on_event: Option<(String, Span)> = None;
            for a in attrs {
                match (a.name.as_str(), &a.value) {
                    ("id", AttrValue::Ident(path)) => id = Some((path.clone(), a.span)),
                    ("onEvent", AttrValue::Ident(m)) => on_event = Some((m.clone(), a.span)),
                    _ => return Err(unknown_attr(name, a)),
                }
            }
            let (path, ispan) = id.ok_or_else(|| err(*span, "<Stream> requires id={someField}"))?;
            let (msg, mspan) =
                on_event.ok_or_else(|| err(*span, "<Stream> requires onEvent={someAction}"))?;
            require_camel_case(&msg, mspan)?;
            let value_ref = display_ref_expr(&path, bound).map_err(|m| err(ispan, m))?;
            Ok(format!(
                "{i}::libra_components::ViewNode::SourceStream {{ {at}\n\
                 {i}    id: ::std::string::ToString::to_string(&{value_ref}), {iat}\n\
                 {i}    on_event: {{ let _: fn(::std::string::String) -> {msg_ty} = {msg_ty}::{variant_ref}; {name_lit}.to_string() }}, {mat}\n\
                 {i}}}",
                at = at(cfg, *span),
                iat = at(cfg, ispan),
                msg_ty = cfg.action,
                variant_ref = pascalize(&msg),
                name_lit = str_lit(&msg),
                mat = at(cfg, mspan),
            ))
        }

        "for" => Err(err(
            *span,
            "<for> is only allowed as a direct child of <Column>/<Row>",
        )),
        "if" => Err(err(
            *span,
            "<if> is only allowed as a direct child of <Column>/<Row>",
        )),
        "else" => Err(err(*span, "<else> is only allowed as a direct child of <if>")),

        other => Err(err(
            *span,
            format!(
                "unknown element <{other}> — available: Column, Row, Text, Button, Chart, Sparkline, Input, Frames, Interval, Stream, for, if"
            ),
        )),
    }
}

/// Mirrors interp's `text_content` exactly: parts joined with a single
/// space when whitespace-separated in source, result trimmed. The
/// interp's runtime algorithm is replayed in generated code so both
/// engines produce identical strings for identical models.
fn gen_text_content(
    children: &[Node],
    cfg: &Config,
    span: Span,
    d: usize,
    bound: &[String],
) -> Result<String, CodegenError> {
    let i = indent(d + 1);
    let mut stmts = String::new();
    for (ci, child) in children.iter().enumerate() {
        let Node::Text(inlines) = child else {
            return Err(err(span, "nested elements inside text content are not allowed in Phase 0"));
        };
        for (j, inline) in inlines.iter().enumerate() {
            if (ci, j) != (0, 0) {
                stmts.push_str(&format!(
                    "{i}if !out.is_empty() && !out.ends_with(' ') {{ out.push(' '); }}\n"
                ));
            }
            match inline {
                Inline::Lit(s) => {
                    stmts.push_str(&format!("{i}out.push_str({});\n", str_lit(s)));
                }
                Inline::Bind { path, span } => {
                    let value_ref = display_ref_expr(path, bound).map_err(|m| err(*span, m))?;
                    stmts.push_str(&format!(
                        "{i}out.push_str(&::std::string::ToString::to_string(&{value_ref})); {}\n",
                        at(cfg, *span)
                    ));
                }
            }
        }
    }
    Ok(format!(
        "{{\n{i}let mut out = ::std::string::String::new();\n{stmts}{i}out.trim().to_string()\n{pad}}}",
        pad = indent(d),
    ))
}

/// Resolve a list of children into an expression producing
/// `Vec<ViewNode>` — `<for>` / `<if>` expand to zero or more siblings
/// (`.extend`), everything else to exactly one (`.push`). Bare text
/// between elements is an error here, same contract as before this
/// helper existed (`parent_name`/`parent_span` are just for that
/// message).
fn gen_children(
    children: &[Node],
    cfg: &Config,
    d: usize,
    bound: &[String],
    parent_name: &str,
    parent_span: Span,
) -> Result<String, CodegenError> {
    if children.iter().any(|c| matches!(c, Node::Text(_))) {
        return Err(err(
            parent_span,
            format!("<{parent_name}> cannot contain bare text; wrap it in <Text>"),
        ));
    }
    let i = indent(d);
    let mut stmts = String::new();
    for c in children {
        if let Node::Element { name, attrs, children: body, span } = c {
            if name == "for" {
                let extend_expr = gen_for(attrs, body, cfg, d, bound, *span)?;
                stmts.push_str(&format!("{i}children.extend({extend_expr});\n"));
                continue;
            }
            if name == "if" {
                let extend_expr = gen_if(attrs, body, cfg, d, bound, *span)?;
                stmts.push_str(&format!("{i}children.extend({extend_expr});\n"));
                continue;
            }
        }
        let child_expr = gen_node(c, cfg, d, bound)?;
        stmts.push_str(&format!("{i}children.push({child_expr});\n"));
    }
    Ok(format!(
        "{{\n{i}let mut children = ::std::vec::Vec::new();\n{stmts}{pad}children\n{pad2}}}",
        pad = indent(d),
        pad2 = indent(d.saturating_sub(1)),
    ))
}

/// `<if test={…}>…<else>…</else></if>` (§6.2 / PLAN-IF + PLAN-ACCESSORS):
/// compiles to a typed Rust `if`. `test` may be a bool field
/// (`state.running`, `state.user.active`) or the `isEmpty` accessor on
/// a string/collection (`state.items.is_empty()`).
fn gen_if(
    attrs: &[Attr],
    body_children: &[Node],
    cfg: &Config,
    d: usize,
    bound: &[String],
    span: Span,
) -> Result<String, CodegenError> {
    let mut test: Option<(String, Span)> = None;
    for a in attrs {
        match (a.name.as_str(), &a.value) {
            ("test", AttrValue::Ident(path)) => test = Some((path.clone(), a.span)),
            _ => return Err(unknown_attr("if", a)),
        }
    }
    let (path, tspan) = test.ok_or_else(|| err(span, "<if> requires test={someBoolField}"))?;
    let root = path.split('.').next().unwrap_or(path.as_str());
    if bound.iter().any(|b| b == root) {
        return Err(err(
            tspan,
            format!("<if>: test={{{path}}} — loop-bound tests aren't supported in v1"),
        ));
    }
    let cond = if_condition_expr(&path).map_err(|m| err(tspan, m))?;
    let (then_kids, else_kids) = split_if_branches(body_children, span)?;
    let then_expr = gen_children(then_kids, cfg, d + 1, bound, "if", span)?;
    let else_expr = gen_children(else_kids, cfg, d + 1, bound, "if", span)?;
    Ok(format!("if {cond} {{ {then_expr} }} else {{ {else_expr} }}"))
}

/// Rust boolean expression for `<if test={path}>`.
fn if_condition_expr(path: &str) -> Result<String, String> {
    let path = strip_accessor_parens(path);
    if let Some((base, acc)) = split_whitelist_accessor(path) {
        return match acc {
            "isEmpty" => Ok(format!("state.{base}.is_empty()")),
            "len" => Err(format!(
                "<if>: test={{{path}}} — `len` is not a bool; use `isEmpty` \
                 or a bool field"
            )),
            _ => unreachable!(),
        };
    }
    Ok(format!("state.{path}"))
}

/// Partition `<if>` children into then / else. At most one `<else>`;
/// it may only appear as a direct child and carries no attributes.
fn split_if_branches<'a>(
    children: &'a [Node],
    span: Span,
) -> Result<(&'a [Node], &'a [Node]), CodegenError> {
    let mut else_at: Option<usize> = None;
    for (i, c) in children.iter().enumerate() {
        if let Node::Element { name, .. } = c {
            if name == "else" {
                if else_at.is_some() {
                    return Err(err(span, "<if> allows at most one <else>"));
                }
                else_at = Some(i);
            }
        }
    }
    match else_at {
        None => Ok((children, &[])),
        Some(i) => {
            if i + 1 != children.len() {
                return Err(err(
                    span,
                    "<if>: <else> must be the last child (nothing after </else>)",
                ));
            }
            let Node::Element { attrs, children: else_kids, span: espan, .. } = &children[i] else {
                unreachable!()
            };
            if !attrs.is_empty() {
                return Err(err(*espan, "<else> takes no attributes"));
            }
            Ok((&children[..i], else_kids))
        }
    }
}

/// `<for each={path} as="name" key={...}>` (§6.2): compiles to
/// `{state-or-bound}.{path}.iter().flat_map(|name| { ...body Vec... })`.
///
/// `key` is the loop variable itself or one field on it (`key={name.id}`
/// — PLAN-ITEM-FIELDS). Nested paths and keys that don't name the loop
/// variable are span-diagnosed errors. Iterating a loop-bound collection
/// (nested `<for>` over a `Vec<Vec<T>>`) isn't supported.
fn gen_for(
    attrs: &[Attr],
    body_children: &[Node],
    cfg: &Config,
    d: usize,
    bound: &[String],
    span: Span,
) -> Result<String, CodegenError> {
    let mut each: Option<(String, Span)> = None;
    let mut as_name: Option<String> = None;
    let mut key: Option<(String, Span)> = None;
    for a in attrs {
        match (a.name.as_str(), &a.value) {
            ("each", AttrValue::Ident(path)) => each = Some((path.clone(), a.span)),
            ("as", AttrValue::Str(s)) => as_name = Some(s.clone()),
            ("key", AttrValue::Ident(k)) => key = Some((k.clone(), a.span)),
            _ => return Err(unknown_attr("for", a)),
        }
    }
    let (path, _espan) = each.ok_or_else(|| err(span, "<for> requires each={someCollection}"))?;
    let as_name =
        as_name.ok_or_else(|| err(span, "<for> requires as=\"name\" (the loop variable)"))?;
    let (key_path, kspan) = key
        .ok_or_else(|| err(span, "<for> requires key={...} — identity for reordering (§6.2)"))?;
    validate_loop_key(&key_path, &as_name, kspan)?;
    let root = path.split('.').next().unwrap_or(&path);
    if bound.iter().any(|b| b == root) {
        return Err(err(
            span,
            format!("<for>: each={{{path}}} — iterating a loop-bound value isn't supported yet"),
        ));
    }

    let mut inner_bound = bound.to_vec();
    inner_bound.push(as_name.clone());
    let body = gen_children(body_children, cfg, d + 1, &inner_bound, "for", span)?;
    Ok(format!("state.{path}.iter().flat_map(|{as_name}| {body})"))
}

/// `key={as}` or `key={as.field}` — one field segment only (§6.2).
fn validate_loop_key(key_path: &str, as_name: &str, span: Span) -> Result<(), CodegenError> {
    if key_path == as_name {
        return Ok(());
    }
    let Some(field) = key_path.strip_prefix(&format!("{as_name}.")) else {
        return Err(err(
            span,
            format!(
                "<for>: key={{{key_path}}} — key must be {{{as_name}}} or {{{as_name}.field}}"
            ),
        ));
    };
    if field.is_empty() || field.contains('.') {
        return Err(err(
            span,
            format!(
                "<for>: key={{{key_path}}} — only one field segment is supported \
                 (got {{{as_name}.field}}, not nested paths)"
            ),
        ));
    }
    Ok(())
}

/// A binding path's Rust expression when it will be used behind `&`
/// for a `ToString`/Display context (text content, `Input::value`).
/// Loop-bound roots (§6.2) resolve to the bare loop variable — `&x`
/// where `x: &T` still satisfies `ToString` via std's blanket `impl<T:
/// Display> Display for &T` applied twice, so no deref is needed here
/// (contrast `typed_value_expr`, which does need one).
///
/// Loop-scoped field paths (`t.id`) emit as Rust field access on the
/// iterator item (PLAN-ITEM-FIELDS). Nested paths (`t.a.b`) are rejected.
/// Top-level dots (`user.name`) and accessors (`items.len` /
/// `items.isEmpty`, optional `()`) emit as `state.…` (PLAN-ACCESSORS).
fn display_ref_expr(path: &str, bound: &[String]) -> Result<String, String> {
    let path = strip_accessor_parens(path);
    if let Some((base, acc)) = split_whitelist_accessor(path) {
        let root = base.split('.').next().unwrap_or(base);
        if bound.iter().any(|b| b == root) {
            return Err(format!(
                "'{path}' — accessors on loop-bound values aren't supported yet; \
                 bind a State field or use a projection"
            ));
        }
        let base_expr = format!("state.{base}");
        return Ok(match acc {
            "len" => format!("{base_expr}.len()"),
            "isEmpty" => format!("{base_expr}.is_empty()"),
            _ => unreachable!(),
        });
    }
    let root = path.split('.').next().unwrap_or(path);
    if bound.iter().any(|b| b == root) {
        let parts: Vec<&str> = path.split('.').collect();
        if parts.len() > 2 {
            return Err(format!(
                "'{path}' — only one loop-bound field segment is supported \
                 ({{loopVar.field}}, not nested paths)"
            ));
        }
        Ok(path.to_string())
    } else {
        Ok(format!("state.{path}"))
    }
}

/// `{items.len}` / `{items.len()}` → (`items`, `len`). Only the
/// PLAN-ACCESSORS whitelist (`len`, `isEmpty`).
fn split_whitelist_accessor(path: &str) -> Option<(&str, &str)> {
    let (base, last) = path.rsplit_once('.')?;
    if last == "len" || last == "isEmpty" {
        Some((base, last))
    } else {
        None
    }
}

fn strip_accessor_parens(path: &str) -> &str {
    path.strip_suffix("()").unwrap_or(path)
}

/// A binding path's Rust expression when the caller needs the actual
/// typed value, not a reference (`Chart`/`Sparkline`'s `handle:`).
/// Loop-bound roots deref the `.iter()` reference — the bound value
/// must be `Copy` (true for `SeriesHandle`, the chart use case).
/// Dot-path access into a loop-bound value isn't supported here:
/// Chart needs the whole handle, not a field of it.
fn typed_value_expr(path: &str, bound: &[String]) -> Result<String, String> {
    let root = path.split('.').next().unwrap_or(path);
    if bound.iter().any(|b| b == root) {
        if path.contains('.') {
            return Err(format!(
                "'{path}' — loop-bound sub-field access isn't supported for typed \
                 props; bind the whole loop variable instead"
            ));
        }
        Ok(format!("*{path}"))
    } else {
        Ok(format!("state.{path}"))
    }
}

fn unknown_attr(el: &str, a: &Attr) -> CodegenError {
    err(a.span, format!("unknown or invalid attribute '{}' on <{el}>", a.name))
}

fn f32_lit(v: f32) -> String {
    format!("{v}f32")
}

fn str_lit(s: &str) -> String {
    format!("{s:?}")
}

fn opt_str(s: &Option<String>) -> String {
    match s {
        Some(v) => format!("::core::option::Option::Some({}.to_string())", str_lit(v)),
        None => "::core::option::Option::None".to_string(),
    }
}

